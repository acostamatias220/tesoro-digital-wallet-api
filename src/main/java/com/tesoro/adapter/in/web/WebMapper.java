package com.tesoro.adapter.in.web;

import com.tesoro.adapter.in.web.dto.AccountDtos.AccountResponse;
import com.tesoro.adapter.in.web.dto.AccountDtos.MovementLineResponse;
import com.tesoro.adapter.in.web.dto.AccountDtos.PostingResponse;
import com.tesoro.adapter.in.web.dto.AccountDtos.TransactionResponse;
import com.tesoro.adapter.in.web.dto.AdminDtos.AuditEntryResponse;
import com.tesoro.adapter.in.web.dto.AdminDtos.OutboxMessageResponse;
import com.tesoro.adapter.in.web.dto.AdminDtos.ReconciliationResponse;
import com.tesoro.adapter.in.web.dto.AdminDtos.SystemAccountResponse;
import com.tesoro.adapter.in.web.dto.AdminDtos.UserResponse;
import com.tesoro.adapter.in.web.dto.AuthDtos.MeResponse;
import com.tesoro.adapter.in.web.dto.OperationDtos.MovementResponse;
import com.tesoro.adapter.in.web.dto.OperationDtos.QuoteResponse;
import com.tesoro.adapter.in.web.dto.OperationDtos.WalletChangeResponse;
import com.tesoro.application.model.AccountMovement;
import com.tesoro.application.model.AuditEntry;
import com.tesoro.application.model.ConversionQuote;
import com.tesoro.application.model.MovementResult;
import com.tesoro.application.model.OutboxMessage;
import com.tesoro.application.model.ReconciliationReport;
import com.tesoro.application.model.SystemAccountBalance;
import com.tesoro.application.model.TransactionDetails;
import com.tesoro.application.model.UserSummary;
import com.tesoro.application.model.WalletChange;
import com.tesoro.domain.model.Account;
import com.tesoro.domain.model.User;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;

/** Maps application results to API DTOs (implementation generated by MapStruct at compile time). */
@Mapper
public interface WebMapper {

    @Mapping(target = "transactionId", source = "transactionId")
    MovementResponse toResponse(MovementResult result);

    WalletChangeResponse toResponse(WalletChange change);

    @Mapping(target = "id", source = "postingId")
    MovementLineResponse toResponse(AccountMovement movement);

    TransactionResponse toResponse(TransactionDetails details);

    @Mapping(target = "account", source = "accountLabel")
    PostingResponse toResponse(TransactionDetails.Line line);

    QuoteResponse toResponse(ConversionQuote quote);

    MeResponse toMe(User user);

    UserResponse toResponse(UserSummary user);

    SystemAccountResponse toResponse(SystemAccountBalance balance);

    ReconciliationResponse toResponse(ReconciliationReport report);

    AuditEntryResponse toResponse(AuditEntry entry);

    OutboxMessageResponse toResponse(OutboxMessage message);

    /** Account exposes behaviour-oriented accessors (no JavaBean getters), so it is mapped by hand. */
    default AccountResponse toResponse(Account account) {
        return new AccountResponse(
                account.id(), account.currency(), account.balance().amount(), account.status(), account.createdAt());
    }
}
