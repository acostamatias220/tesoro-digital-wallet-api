package com.tesoro.adapter.out.persistence.mapper;

import com.tesoro.adapter.out.persistence.entity.AccountEntity;
import com.tesoro.adapter.out.persistence.entity.AuditLogEntity;
import com.tesoro.adapter.out.persistence.entity.OutboxEventEntity;
import com.tesoro.adapter.out.persistence.entity.RefreshTokenEntity;
import com.tesoro.adapter.out.persistence.entity.UserEntity;
import com.tesoro.application.model.AuditEntry;
import com.tesoro.application.model.OutboxMessage;
import com.tesoro.application.model.RefreshToken;
import com.tesoro.domain.model.Account;
import com.tesoro.domain.model.User;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;

/** Maps JPA entities to domain/application models and back (implementation generated by MapStruct). */
@Mapper
public interface PersistenceMapper {

    User toDomain(UserEntity entity);

    UserEntity toEntity(User user);

    @Mapping(
            target = "balance",
            expression = "java(com.tesoro.domain.model.Money.of(entity.getBalance(), entity.getCurrency()))")
    Account toDomain(AccountEntity entity);

    default AccountEntity toEntity(Account account) {
        AccountEntity entity = new AccountEntity();
        entity.setId(account.id());
        entity.setOwnerId(account.ownerId());
        entity.setCode(account.code());
        entity.setCurrency(account.currency());
        entity.setKind(account.kind());
        entity.setStatus(account.status());
        entity.setBalance(account.balance().amount());
        entity.setCreatedAt(account.createdAt());
        return entity;
    }

    RefreshToken toDomain(RefreshTokenEntity entity);

    RefreshTokenEntity toEntity(RefreshToken token);

    AuditEntry toDomain(AuditLogEntity entity);

    AuditLogEntity toEntity(AuditEntry entry);

    OutboxMessage toDomain(OutboxEventEntity entity);
}
